CLASSES = ("西洋", "漢籍", "同時代日本")
KINDS = ("人名", "地名", "書名", "事物")


def build(data_dir: Path, chapters: list[dict]) -> dict:
    from .dispersion import chapter_index, plain_map

    text, offs = plain_map(data_dir)
    of = chapter_index(chapters)

    # 長い表記から順に照合し、取った範囲は二度使わない(短い語が長い語を食わない)
    entries = sorted(VOCAB, key=lambda v: -len(v[0]))
    taken: list[tuple[int, int]] = []
    rows: list[dict] = []
    for surface, cls, kind, note in entries:
        hits = []
        for m in re.finditer(re.escape(surface), text):
            if any(s <= m.start() < e for s, e in taken):
                continue
            taken.append((m.start(), m.end()))
            hits.append(m.start())
        if not hits:
            rows.append({"surface": surface, "class": cls, "kind": kind, "note": note,
                         "total": 0, "needs_review": True,
                         "reason": "本文にこの表記で現れない"})
            continue
        first = hits[0]
        rows.append({
            "surface": surface,
            "class": cls,
            "kind": kind,
            "note": note,
            "total": len(hits),
            "offsets": [offs[h] for h in hits],
            "by_chapter": _by_chapter(hits, offs, of, chapters),
            "evidence": text[max(0, first - CONTEXT): first + len(surface) + CONTEXT],
            "needs_review": False,
        })
    rows.sort(key=lambda r: (CLASSES.index(r["class"]), KINDS.index(r["kind"]), -r["total"]))
    return {"vocab_size": len(VOCAB), "context": CONTEXT, "entries": rows,
            "classes": list(CLASSES), "kinds": list(KINDS),
            "chapters": [{"index": c["index"], "label": c["label"],
                          "start": c["start"], "end": c["end"], "chars": c["chars"]}
                         for c in chapters]}


def _by_chapter(hits, offs, of, chapters) -> dict:
    counts = {str(c["index"]): 0 for c in chapters}
    for h in hits:
        counts[str(of(offs[h]))] += 1
    return counts


def unclassified_candidates(data_dir: Path, alias: set[str], min_freq: int = 2) -> dict:
    """統制語彙に入れなかった候補の件数(限界を隠さないため)。"""
    import collections

    catalogued = {v[0] for v in VOCAB}
    prop: collections.Counter = collections.Counter()
    for path in sorted((data_dir / "morph" / "gendai").glob("ch*.json")):
        d = json.loads(path.read_text(encoding="utf-8"))
        cols = {c: i for i, c in enumerate(d["cols"])}
        for row in d["rows"]:
            s = row[cols["s"]]
            if row[cols["pos2"]] == "固有名詞" or row[cols["goshu"]] == "外":
                prop[s] += 1
    rest = {
        k: v for k, v in prop.items()
        if v >= min_freq and k not in alias and not any(k in c for c in catalogued)
    }
    return {
        "min_freq": min_freq,
        "candidates": len(rest),
        "occurrences": sum(rest.values()),
        "top": [{"surface": k, "n": v} for k, v in
                sorted(rest.items(), key=lambda kv: -kv[1])[:40]],
        "note": "形態素解析の固有名詞タグは断片(「武」「馳」「致」)を多く拾う。"
                "統制語彙に入れる根拠を持てないものは分類していない",
    }
